// Fills the SDMS download pages with the latest release details.
//
// Every download link already has a working href in the HTML (GitHub's /releases/latest and
// the fixed-name dolilsheba.apk), so the pages work even when this script or both feeds fail;
// the script only upgrades them to the exact file, version, size and release notes.
//
// Bindings (any element, any number of times):
//   data-dl="desktop|mobile"     <a> href → exact installer / APK
//   data-ver="desktop|mobile"    text → "v২.০.২২"
//   data-size="desktop|mobile"   text → "৮৮.৩ MB"
//   data-date="desktop|mobile"   text → "৮ নভেম্বর, ২০২৬"
//   data-file="desktop"          text → installer file name
//   data-notes="desktop|mobile"  <details> with a .notes child; un-hidden when notes exist
//   data-sha="mobile"            text → APK SHA-256
//   data-for="windows|android"   gets class "for-you" on a matching device
//
// Sources: latest.json (desktop) and mobile.json (Android) sit at the site root and are
// regenerated by .github/workflows/update-latest.yml. They are same-origin files, so they cost
// nothing and cannot be throttled. The GitHub API is the desktop fallback only: anonymous
// callers get 60 requests per hour PER IP, after which every request is answered 403.
(function () {
  "use strict";

  var ROOT = new URL("../", document.currentScript.src).href; // site root, from /assets/
  var REPO = "dolil/dolilsheba-releases";
  var API = "https://api.github.com/repos/" + REPO + "/releases/latest";
  var MOBILE_REPO_URL = "https://github.com/dolil/dolilsheba-mobile-releases/";

  // ── Platform: point the visitor at their own device first ──
  var ua = navigator.userAgent || "";
  var platform = /Android/i.test(ua) ? "android" : /Windows/i.test(ua) ? "windows" : "";
  if (platform) {
    document.documentElement.classList.add("is-" + platform);
    each('[data-for="' + platform + '"]', function (el) { el.classList.add("for-you"); });
    each('[data-primary-for="' + platform + '"]', function (el) { el.classList.add("primary"); });
    each('[data-primary-for]:not([data-primary-for="' + platform + '"])', function (el) { el.classList.remove("primary"); });
  }

  function each(sel, fn) { Array.prototype.forEach.call(document.querySelectorAll(sel), fn); }
  function setText(attr, kind, text) { if (text) each("[" + attr + '="' + kind + '"]', function (el) { el.textContent = text; }); }

  var BN = "০১২৩৪৫৬৭৮৯";
  function bn(s) { return String(s).replace(/\d/g, function (d) { return BN[d]; }); }
  function size(b) {
    if (!b) return "";
    if (b < 1048576) return bn((b / 1024).toFixed(1)) + " KB";
    if (b < 1073741824) return bn((b / 1048576).toFixed(1)) + " MB";
    return bn((b / 1073741824).toFixed(2)) + " GB";
  }
  function date(iso) {
    if (!iso) return "";
    try { return new Date(iso).toLocaleDateString("bn-BD", { year: "numeric", month: "long", day: "numeric" }); }
    catch (e) { return ""; }
  }
  function ver(v) { v = String(v || "").replace(/^v/i, ""); return v ? "v" + bn(v) : ""; }
  function escapeHtml(s) {
    return String(s).replace(/[&<>"']/g, function (c) {
      return { "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;" }[c];
    });
  }

  // Release notes are Markdown (## headings, - bullets, **bold**). Everything is escaped FIRST,
  // then only these few tags are added back — nothing in the notes can inject markup.
  function renderNotes(src) {
    var out = [], inList = false;
    function inline(s) {
      return s.replace(/\*\*(.+?)\*\*/g, "<strong>$1</strong>").replace(/`([^`]+)`/g, "<code>$1</code>");
    }
    escapeHtml(src).split(/\r?\n/).forEach(function (raw) {
      var line = raw.trim();
      var li = line.match(/^[-*]\s+(.*)$/);
      if (li) {
        if (!inList) { out.push("<ul>"); inList = true; }
        out.push("<li>" + inline(li[1]) + "</li>");
        return;
      }
      if (inList) { out.push("</ul>"); inList = false; }
      if (!line || /^-{3,}$/.test(line)) return;
      var h = line.match(/^#{1,6}\s+(.*)$/);
      out.push(h ? "<h4>" + inline(h[1]) + "</h4>" : "<p>" + inline(line) + "</p>");
    });
    if (inList) out.push("</ul>");
    return out.join("");
  }
  function showNotes(kind, md) {
    md = (md || "").trim();
    if (!md) return;
    each('[data-notes="' + kind + '"]', function (box) {
      var n = box.querySelector(".notes");
      if (n) n.innerHTML = renderNotes(md);
      box.hidden = false;
    });
  }
  function getJSON(url) {
    return fetch(url + (url.indexOf("?") < 0 ? "?" : "&") + "t=" + Date.now(), { cache: "no-store" })
      .then(function (r) { if (!r.ok) throw new Error(url + " → " + r.status); return r.json(); });
  }

  // ── Desktop (this repo) ──
  function pickSetup(release) {
    var a = release.assets || [];
    return a.filter(function (x) { return /setup.*\.exe$/i.test(x.name); })[0]
        || a.filter(function (x) { return /\.exe$/i.test(x.name); })[0] || null;
  }
  getJSON(ROOT + "latest.json")
    .then(function (d) { if (!d || !Array.isArray(d.assets)) throw new Error("bad feed"); return d; })
    .catch(function () {
      return fetch(API, { headers: { Accept: "application/vnd.github+json" } })
        .then(function (r) { if (!r.ok) throw new Error("GitHub API " + r.status); return r.json(); });
    })
    .then(function (r) {
      var setup = pickSetup(r);
      setText("data-ver", "desktop", ver(r.name || r.tag_name));
      setText("data-date", "desktop", date(r.published_at));
      if (setup) {
        each('[data-dl="desktop"]', function (a) { a.href = setup.browser_download_url; });
        setText("data-size", "desktop", size(setup.size));
        setText("data-file", "desktop", setup.name);
      }
      showNotes("desktop", r.body);
    })
    .catch(function (err) { console.warn("Desktop release details unavailable:", err); });

  // ── Android (dolil/dolilsheba-mobile-releases) ──
  // That repo's latest.json is a release ASSET; release downloads carry no CORS headers, so CI
  // copies it here as mobile.json.
  getJSON(ROOT + "mobile.json")
    .then(function (m) {
      var apk = (m && m.apk) || {};
      // Only ever link to an APK published in the mobile releases repo.
      if (String(apk.url || "").indexOf(MOBILE_REPO_URL) !== 0) throw new Error("unexpected APK url");
      each('[data-dl="mobile"]', function (a) { a.href = apk.url; });
      setText("data-ver", "mobile", ver(m.version));
      setText("data-size", "mobile", size(apk.size));
      setText("data-date", "mobile", date(m.published_at));
      if (apk.sha256) setText("data-sha", "mobile", "SHA-256: " + apk.sha256);
      showNotes("mobile", m.notes);
    })
    .catch(function (err) { console.warn("Android release details unavailable:", err); });
})();
